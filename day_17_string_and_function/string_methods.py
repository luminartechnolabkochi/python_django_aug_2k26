"""
string methods

upper() => convert string to uppercase 
lower()=> convert string object to lower case
isdigit()=> return true if string object contain only numbers return false otherwise
isalpha()=> return true if string object contain only alphabets return false otherwise
isalnum() => return true if string object contain only alphabet and digits
"""



company_name = "luminar technolab"

print(company_name.upper())


employee_name = "RAHUL VA"

print(employee_name.lower())

vehicle_number = "1919"

print(vehicle_number.isdigit())

chasis_number="wertyuiop"

print(chasis_number.isalpha())

pan_card_number="dtz-ps6463j"

print(pan_card_number.isalnum())

